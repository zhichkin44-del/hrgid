def ticket_accepted(
    label: str, sla_hours: int, due_phrase: str, closed_note: str, in_hours: bool
) -> str:
    base = f"Обращение {label} принято\nСтатус: в очереди. Срок ответа — {sla_hours} рабочих часа. "
    if in_hours:
        base += f"Ответ придёт {due_phrase} — прямо в этот чат."
    else:
        base += f"{closed_note}\nОтвет придёт {due_phrase} — прямо в этот чат."
    return base + "\nДописать детали можно в «Мои обращения»."


