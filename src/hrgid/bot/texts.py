def money(x: Decimal, kopecks: bool = True) -> str:
    q = x.quantize(Decimal("0.01")) if kopecks else x.quantize(Decimal(1))
    s = f"{q:,.2f}" if kopecks else f"{q:,.0f}"
    return s.replace(",", " ").replace(".", ",") + " ₽"
