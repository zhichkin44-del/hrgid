def render_fragments(hits: list[SearchHit]) -> str:
    return "\n".join(
        f'<fragment id="{h.id}" ref="{h.ref}" source="{"закон" if h.tenant_id == "law" else "правила компании"}">'
        f"\n{h.text}\n</fragment>"
        for h in hits
    )


def history_block(history: list[str]) -> str:
    if not history:
        return ""
    lines = "\n".join(f"- {q}" for q in history)
    return f"<history>\nПредыдущие вопросы сотрудника:\n{lines}\n</history>\n"


def route_user(question: str, history: list[str]) -> str:
    return f"{history_block(history)}<question>\n{question}\n</question>"


def answer_user(question: str, history: list[str], hits: list[SearchHit], feedback: str) -> str:
    fb = f"\nПредыдущая попытка отклонена проверкой: {feedback}\nИсправь.\n" if feedback else ""
    return (
        f"{history_block(history)}<fragments>\n{render_fragments(hits)}\n</fragments>\n"
        f"<question>\n{question}\n</question>{fb}"
    )


def support_user(claim: str, quote: str) -> str:
    return f"Утверждение: {claim}\nЦитата: {quote}"
